// --- scenario: unused definition warns, success preserved ---------------

#[test]
fn unused_helper_warns_on_the_warnings_channel_and_succeeds() {
    let spec = with_fragment_section(
        "def is_short:\n\n```rust\nfn is_short(s: &str) -> bool { s.len() < 3 }\n```\n\ndef is_unused:\n\n```rust\nfn is_unused() -> bool { true }\n```\n",
    );
    // p1/p2 no longer reference is_short in this variant? They do —
    // with_fragment_section only replaces the defs; the base's @is_short
    // references stay live. is_unused is the dead one.
    let compiled = compile_spec(&spec).unwrap_p();
    let dir = std::env::temp_dir().join(format!("spk-frag-warn-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let written = write_artifacts(&spec, &compiled, dir.to_str().unwrap_p()).unwrap_p();
    assert!(
        written.warnings.iter().any(|w| w.contains("is_unused")),
        "dead-helper warning names the unused def: {:?}",
        written.warnings
    );
    assert!(
        !written.warnings.iter().any(|w| w.contains("is_short")),
        "the live helper is not warned: {:?}",
        written.warnings
    );
    let _ = std::fs::remove_dir_all(&dir);
}

// --- task 1.6: the linter treats ## Fragments as opaque prose -----------

#[test]
fn fragments_section_lints_clean_as_opaque_prose() {
    let report = lint::lint_corpus(&[helpers_spec()]);
    let issues: Vec<_> = report
        .issues
        .iter()
        .filter(|i| i.file == "demo.helpers")
        .collect();
    assert!(
        issues.is_empty(),
        "no gating rule fires on the section: {issues:?}"
    );
    assert!(
        report
            .warnings
            .iter()
            .all(|w| !w.message.contains("Fragments")),
        "the section disturbs no advisory either: {:?}",
        report.warnings
    );
}

